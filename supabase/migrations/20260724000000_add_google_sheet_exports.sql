-- Google Sheets publication state and coalescing queue.

-- Some deployments use the legacy host_user_id column without having the
-- original users table in their migration history. Keep this migration
-- self-contained so organizer OAuth has a stable local user record to attach
-- to. Existing users tables are left untouched apart from the auth link below.
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.users
  add column if not exists auth_user_id uuid unique;

-- Existing tournaments use host_user_id = 1 by default. Seed that compatibility
-- record only when the table is newly empty; real organizer email is stored by
-- the OAuth callback after sign-in.
insert into public.users (id, email)
overriding system value
select 1, 'legacy-host@tftourney.local'
where not exists (select 1 from public.users);

create table if not exists public.organizer_google_connections (
  id uuid primary key default gen_random_uuid(),
  user_id bigint not null unique references public.users(id) on delete cascade,
  google_email text,
  scopes text[] not null default '{}',
  encrypted_refresh_token text,
  status text not null default 'connected'
    check (status in ('connected', 'needs_reauth', 'disconnected')),
  last_error_code text,
  last_error_message text,
  connected_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

do $$
declare
  tournament_id_type text;
begin
  if to_regclass('public.tournament_sheet_exports') is null then
    select format_type(a.atttypid, a.atttypmod)
    into tournament_id_type
    from pg_attribute a
    where a.attrelid = 'public.tournaments'::regclass
      and a.attname = 'id'
      and not a.attisdropped;

    if tournament_id_type is null then
      raise exception 'public.tournaments.id is required before Google Sheets exports can be installed.';
    end if;

    execute format($sql$
      create table public.tournament_sheet_exports (
        id uuid primary key default gen_random_uuid(),
        tournament_id %s not null unique references public.tournaments(id) on delete cascade,
        host_user_id bigint not null default 1,
        spreadsheet_id text unique,
        spreadsheet_url text,
        players_sheet_id integer,
        scores_sheet_id integer,
        checkmate_sheet_id integer,
        state text not null default 'queued'
          check (state in ('queued', 'syncing', 'ready', 'error', 'needs_reauth')),
        desired_revision bigint not null default 1 check (desired_revision >= 0),
        synced_revision bigint not null default 0 check (synced_revision >= 0),
        dirty_at timestamptz not null default now(),
        last_synced_at timestamptz,
        next_attempt_at timestamptz,
        retry_count integer not null default 0 check (retry_count >= 0),
        lease_until timestamptz,
        last_error_code text,
        last_error_message text,
        created_at timestamptz not null default now(),
        updated_at timestamptz not null default now(),
        constraint tournament_sheet_exports_revision_order check (synced_revision <= desired_revision)
      )
    $sql$, tournament_id_type);
  end if;
end $$;

